def r(): return START + len(rows)
def add(kind, B="", C="", D="", E="", F="", G="", H="", I="", J="", K=""):
    rows.append([B, C, D, E, F, G, H, I, J, K]); kinds.append(kind); return r() - 1
def item(desc, unit, qty, rate, star=False, key=None):
    n = r()
    add("item", "", "⭐️" if star else "", desc, "", "", unit, qty, rate, f"=H{n}*I{n}")
    if key: refs[key] = n
    return n
def join(desc, W, D, H, rate_expr, star=False, key=None):
    n = r()
    I = rate_expr.replace("W", f"E{n}").replace("HH", f"G{n}")
    add("join", "", "⭐️" if star else "", desc, W, D, H, 1, f"=ROUND({I},2)", f"=H{n}*I{n}")
    if key: refs[key] = n
    return n
def sub(t): add("sub", "", "", t)
def note(t): add("note", "", "", t)
def blank(): add("blank")
